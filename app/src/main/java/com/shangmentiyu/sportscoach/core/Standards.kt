        "13" to "中考",
    )

    /** 年级编码转中文显示名 */
    fun gradeLabel(code: String): String {
        for ((c, label) in GRADE_OPTIONS) {
            if (c == code) return label
        }
        return if (code.isEmpty()) "学龄前" else "年级${code}"
    }

    /** 根据年级编码获取标准列表（统一入口）
     *  学龄前(0/空) 无体测标准，返回空列表 */
    fun getStandardsByGrade(code: String): List<Std> {
        val g = code.toIntOrNull() ?: 0
        if (g == 0) return emptyList()  // 学龄前无体测标准
        if (g == 13) return ZHONGKAO_2026
        if (g in 7..9) return JUNIOR_DATA[g] ?: emptyList()
        if (g in 10..12) return SENIOR_DATA[g] ?: emptyList()
        return PRIMARY_DATA[g] ?: emptyList()
    }

    /** 在标准列表中按项目名查找 */
    fun findStd(stds: List<Std>, name: String): Std? {
        return stds.find { it.name == name }
    }
